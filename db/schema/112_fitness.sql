-- ── The view every screen reads: a workout with all of its facts ─────────────
CREATE VIEW fitness.workout_sessions AS
SELECT w.workout_id, w.workout_date, w.started_at, w.activity_type, t.label AS activity_label, w.category,
       k.label AS category_label, COALESCE(NULLIF(w.title, ''), t.label) AS name, w.title, w.minutes, w.note,
       t.counts_toward_goal, w.source, w.source_ref, w.details, w.created_at, w.updated_at,
       c.distance, c.distance_unit, c.distance_km, COALESCE(c.elevation_gain_m, r.elevation_gain_m) AS elevation_gain_m,
       c.calories, c.avg_heart_rate,
       r.workout_id IS NOT NULL AS has_route, r.started_at AS route_started_at,
       COALESCE((SELECT jsonb_agg(jsonb_strip_nulls(jsonb_build_object('lift', s.lift, 'sets', s.sets, 'reps', s.reps,
                                                                        'weight_lb', s.weight_lb)) ORDER BY s.position)
                 FROM fitness.workout_strength s WHERE s.workout_id = w.workout_id), '[]') AS lifts,
       (SELECT to_jsonb(h) - 'workout_id' - 'category' FROM fitness.workout_hiit h WHERE h.workout_id = w.workout_id) AS circuit
FROM fitness.workouts w
JOIN fitness.activity_types t USING (activity_type)
JOIN fitness.categories k ON k.category = w.category
LEFT JOIN fitness.workout_cardio c USING (workout_id)
LEFT JOIN fitness.workout_routes r USING (workout_id);

-- ── Health's views, as in 20_health.sql, on fitness ─────────────────────────
CREATE VIEW health.daily_activity AS
WITH days AS (
    SELECT workout_date AS day FROM fitness.workouts
    UNION SELECT meal_date FROM journal.meals
    UNION SELECT measured_on FROM health.body_measurements
    UNION SELECT drink_date FROM health.alcohol
    UNION SELECT log_date FROM health.daily_logs
    UNION SELECT entry_date FROM journal.entries
), workouts AS (
    SELECT w.workout_date AS day,
           COALESCE(SUM(w.minutes) FILTER (WHERE t.counts_toward_goal), 0) AS workout_minutes,
           COUNT(*) FILTER (WHERE t.counts_toward_goal) AS workout_sessions,
           COALESCE(SUM(w.minutes) FILTER (WHERE NOT t.counts_toward_goal), 0) AS dog_walk_minutes,
           -- By kind, from the base table; distance from the cardio facts.
           COALESCE(SUM(w.minutes) FILTER (WHERE w.category = 'cardio' AND t.counts_toward_goal), 0) AS cardio_minutes,
           COALESCE(SUM(w.minutes) FILTER (WHERE w.category = 'strength'), 0) AS strength_minutes,
           COALESCE(SUM(w.minutes) FILTER (WHERE w.category = 'hiit'), 0) AS hiit_minutes,
           COALESCE(SUM(w.minutes) FILTER (WHERE w.category = 'mobility'), 0) AS mobility_minutes,
           SUM(c.distance_km) FILTER (WHERE w.activity_type = 'run') AS run_km,
           SUM(c.distance_km) AS cardio_km
    FROM fitness.workouts w JOIN fitness.activity_types t USING (activity_type)
    LEFT JOIN fitness.workout_cardio c USING (workout_id)
    GROUP BY w.workout_date
), meals AS (
    SELECT meal_date AS day,
           COUNT(*) FILTER (WHERE status = 'eaten') AS meals_eaten,
           COUNT(*) FILTER (WHERE status = 'planned') AS meals_planned,
           SUM(calories) FILTER (WHERE status = 'eaten') AS meal_calories,
           SUM(calories) FILTER (WHERE status = 'planned') AS planned_calories,
           SUM(protein_g) FILTER (WHERE status = 'eaten') AS protein_g,
           SUM(carbs_g) FILTER (WHERE status = 'eaten') AS carbs_g,
           SUM(fat_g) FILTER (WHERE status = 'eaten') AS fat_g,
           SUM(fiber_g) FILTER (WHERE status = 'eaten') AS fiber_g
    FROM journal.meals GROUP BY meal_date
), drinks AS (
    SELECT drink_date AS day, SUM(containers) AS beers, SUM(standard_drinks) AS standard_drinks,
           SUM(calories) AS alcohol_calories
    FROM health.alcohol GROUP BY drink_date
), weigh_ins AS (
    SELECT measured_on AS day,
           COUNT(*) AS weigh_ins,
           COUNT(*) FILTER (WHERE is_morning) AS morning_weigh_ins,
           (ARRAY_AGG(value_lb ORDER BY measured_at NULLS FIRST, measurement_id))[1] AS first_weight,
           (ARRAY_AGG(value_lb ORDER BY measured_at DESC NULLS LAST, measurement_id DESC))[1] AS weight,
           'lb'::text AS weight_unit,
           (ARRAY_AGG(is_morning ORDER BY measured_at DESC NULLS LAST, measurement_id DESC))[1] AS weight_is_morning,
           MIN(value_lb) AS min_weight,
           MAX(value_lb) AS max_weight,
           ROUND(AVG(value_lb) FILTER (WHERE is_morning), 1) AS morning_weight
    FROM health.body_measurements WHERE metric = 'weight'
    GROUP BY measured_on
), profile AS (
    SELECT * FROM health.profile WHERE profile_id = 1
)
SELECT d.day,
       c.iso_weekday,
       c.week_start,
       COALESCE(w.workout_minutes, 0) AS workout_minutes,
       COALESCE(w.workout_sessions, 0) AS workout_sessions,
       COALESCE(w.dog_walk_minutes, 0) AS dog_walk_minutes,
       COALESCE(w.cardio_minutes, 0) AS cardio_minutes,
       COALESCE(w.strength_minutes, 0) AS strength_minutes,
       COALESCE(w.hiit_minutes, 0) AS hiit_minutes,
       COALESCE(w.mobility_minutes, 0) AS mobility_minutes,
       w.run_km, w.cardio_km,
       COALESCE(w.workout_minutes, 0) >= COALESCE(
           (SELECT target FROM health.goals WHERE metric = 'qualifying_workout_minutes'), 45) AS qualifying_workout_day,
       COALESCE(m.meals_eaten, 0) AS meals_eaten,
       COALESCE(m.meals_planned, 0) AS meals_planned,
       m.meal_calories, m.planned_calories, m.protein_g, m.carbs_g, m.fat_g, m.fiber_g,
       COALESCE(dr.beers, 0) AS beers,
       COALESCE(dr.standard_drinks, 0) AS standard_drinks,
       dr.alcohol_calories,
       CASE WHEN m.meal_calories IS NULL AND dr.alcohol_calories IS NULL THEN NULL
            ELSE COALESCE(m.meal_calories, 0) + COALESCE(dr.alcohol_calories, 0) END AS total_calories,
       (SELECT calorie_target FROM profile) AS calorie_target,
       COALESCE(l.nutrition_complete, false) AS nutrition_complete,
       COALESCE(dr.beers, 0) = 0
           OR (dr.beers < COALESCE((SELECT drink_boundary FROM profile), 3)
               AND c.iso_weekday = ANY (COALESCE((SELECT alcohol_days FROM profile), '{5,6,7}'::smallint[]))) AS alcohol_within_rules,
       COALESCE(wi.weigh_ins, 0) AS weigh_ins,
       COALESCE(wi.morning_weigh_ins, 0) AS morning_weigh_ins,
       wi.first_weight, wi.weight, wi.weight_unit, wi.weight_is_morning,
       wi.min_weight, wi.max_weight, wi.morning_weight,
       e.entry_date IS NOT NULL AS has_journal_entry
FROM days d
JOIN core.calendar c ON c.day = d.day
LEFT JOIN workouts w ON w.day = d.day
LEFT JOIN meals m ON m.day = d.day
LEFT JOIN drinks dr ON dr.day = d.day
LEFT JOIN weigh_ins wi ON wi.day = d.day
LEFT JOIN health.daily_logs l ON l.log_date = d.day
LEFT JOIN journal.entries e ON e.entry_date = d.day;

CREATE VIEW health.weekly_workout_progress AS
SELECT week_start,
       COUNT(*) FILTER (WHERE qualifying_workout_day) AS qualifying_days,
       SUM(workout_minutes) AS workout_minutes,
       SUM(dog_walk_minutes) AS dog_walk_minutes,
       SUM(beers) AS beers,
       SUM(standard_drinks) AS standard_drinks,
       COUNT(*) FILTER (WHERE NOT alcohol_within_rules) AS days_outside_alcohol_rules,
       (SELECT target FROM health.goals WHERE metric = 'workout_days_per_week') AS target_days,
       COUNT(*) FILTER (WHERE qualifying_workout_day)
           >= COALESCE((SELECT target FROM health.goals WHERE metric = 'workout_days_per_week'), 5) AS goal_met
FROM health.daily_activity
GROUP BY week_start;

-- Morning weigh-ins drive the trend, as in the Health tracker; others stay as references.
CREATE VIEW health.weight_trend AS
SELECT day, weigh_ins, weight, weight_unit, weight_is_morning, min_weight, max_weight, morning_weight,
       ROUND(AVG(morning_weight) OVER seven_days, 1) AS morning_avg_7d,
       ROUND(COALESCE(AVG(morning_weight) OVER seven_days, weight) * 0.45359237
             / NULLIF(((SELECT height_in FROM health.profile) * 0.0254) ^ 2, 0), 1) AS bmi
FROM health.daily_activity
WHERE weight IS NOT NULL
WINDOW seven_days AS (ORDER BY day RANGE BETWEEN INTERVAL '6 days' PRECEDING AND CURRENT ROW);

CREATE VIEW health.goal_progress AS
SELECT g.metric, g.target, g.unit, g.period, g.direction, c.current_value,
       CASE WHEN c.current_value IS NULL THEN NULL
            WHEN g.direction = 'at_least' THEN c.current_value >= g.target
            WHEN g.direction = 'below' THEN c.current_value < g.target
            ELSE c.current_value <= g.target END AS met
FROM health.goals g
LEFT JOIN LATERAL (
    SELECT CASE g.metric
        WHEN 'workout_days_per_week' THEN (
            SELECT qualifying_days::numeric FROM health.weekly_workout_progress
            WHERE week_start = date_trunc('week', current_date)::date)
        WHEN 'qualifying_workout_minutes' THEN (
            SELECT workout_minutes FROM health.daily_activity WHERE day = current_date)
        WHEN 'weight' THEN (
            SELECT COALESCE(morning_avg_7d, weight) FROM health.weight_trend ORDER BY day DESC LIMIT 1)
        WHEN 'bmi' THEN (
            SELECT bmi FROM health.weight_trend ORDER BY day DESC LIMIT 1)
        WHEN 'daily_calories' THEN (
            SELECT total_calories FROM health.daily_activity WHERE day = current_date)
        WHEN 'beers_per_day' THEN (
            SELECT beers FROM health.daily_activity WHERE day = current_date)
    END AS current_value
) c ON true;

-- ── Habits' views, as in 111_daily_habits.sql, on fitness ──────────────────
-- What the day's records say, for the habits that tick themselves (NULL: no record, or no rule).
CREATE VIEW journal.derived_habits AS
SELECT c.day, h.habit,
       CASE h.derived_from
           WHEN 'strength_workout' THEN EXISTS (SELECT 1 FROM fitness.workouts w
                                                WHERE w.workout_date = c.day AND w.category = 'strength')
           WHEN 'run_workout' THEN EXISTS (SELECT 1 FROM fitness.workouts w
                                           WHERE w.workout_date = c.day AND w.activity_type = 'run')
           WHEN 'alcohol' THEN EXISTS (SELECT 1 FROM health.alcohol a WHERE a.drink_date = c.day AND a.containers > 0)
       END AS done
FROM core.calendar c CROSS JOIN journal.habits h
WHERE h.derived_from IS NOT NULL;

-- Each day's habits, a row per habit for the screens: what the owner set, else what the day's records show.
CREATE VIEW journal.day_habits AS
SELECT c.day, h.habit, h.label, h.polarity, h.derived_from, h.position,
       COALESCE((to_jsonb(m) ->> h.habit)::boolean, d.done, false) AS done,
       CASE WHEN to_jsonb(m) ->> h.habit IS NOT NULL THEN 'manual' WHEN d.done THEN 'derived' ELSE 'none' END AS origin
FROM core.calendar c
CROSS JOIN journal.habits h
LEFT JOIN journal.daily_habits m ON m.day = c.day
LEFT JOIN journal.derived_habits d ON d.day = c.day AND d.habit = h.habit;

-- The same, a column per habit: every day with a habit set or ticked. Made from journal.habits, so a habit
-- added there (with its column) appears once journal.make_habit_days() runs again.
CREATE OR REPLACE FUNCTION journal.make_habit_days() RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    cols text;
BEGIN
    SELECT string_agg(format('bool_or(done) FILTER (WHERE habit = %L) AS %I', habit, habit), ', ' ORDER BY position, habit)
    INTO cols FROM journal.habits;
    EXECUTE 'DROP VIEW IF EXISTS journal.habit_days';
    EXECUTE format($v$CREATE VIEW journal.habit_days AS
                      SELECT day, %s,
                             COUNT(*) FILTER (WHERE done AND polarity = 'build') AS habits_built,
                             COUNT(*) FILTER (WHERE done AND polarity = 'limit') AS habits_to_limit
                      FROM journal.day_habits
                      WHERE day IN (SELECT day FROM journal.daily_habits
                                    UNION SELECT workout_date FROM fitness.workouts
                                    UNION SELECT drink_date FROM health.alcohol)
                      GROUP BY day$v$, cols);
END $$;
SELECT journal.make_habit_days();

-- The cross-domain day, as in 111_daily_habits.sql: with habits from the day's own row and its records.
CREATE VIEW core.daily_summary AS
WITH active_days AS (
    SELECT day FROM health.daily_activity
    UNION SELECT day FROM journal.daily_habits
    UNION SELECT day FROM finance.spending
    UNION SELECT posted_on FROM finance.transactions
    UNION SELECT observed_on FROM garden.plant_observations
    UNION SELECT post_date FROM content.blog_posts
    UNION SELECT received_on FROM content.messages
), spend AS (
    SELECT day, SUM(amount) AS spending FROM finance.spending GROUP BY day
), income AS (
    SELECT t.posted_on AS day, SUM(-t.amount) AS income_received
    FROM finance.transactions t JOIN finance.movement_types mt USING (movement_type)
    WHERE mt.flow = 'income' GROUP BY t.posted_on
)
SELECT c.day, c.iso_weekday, c.week_start, c.month_start,
       e.entry_id IS NOT NULL AS has_journal_entry,
       COALESCE(h.habits_built, 0) AS habits_built,
       COALESCE(h.habits_to_limit, 0) AS habits_to_limit,
       COALESCE(a.workout_minutes, 0) AS workout_minutes,
       COALESCE(a.qualifying_workout_day, false) AS qualifying_workout_day,
       a.total_calories,
       a.calorie_target,
       COALESCE(a.beers, 0) AS beers,
       a.weight,
       COALESCE(s.spending, 0) AS spending,
       COALESCE(i.income_received, 0) AS income_received,
       (SELECT COUNT(*) FROM garden.plant_observations o WHERE o.observed_on = c.day) AS garden_observations,
       (SELECT COUNT(*) FROM content.blog_posts p WHERE p.post_date = c.day AND p.published) AS posts_published
FROM active_days d
JOIN core.calendar c ON c.day = d.day
LEFT JOIN journal.entries e ON e.entry_date = c.day
LEFT JOIN LATERAL (SELECT COUNT(*) FILTER (WHERE dh.done AND dh.polarity = 'build') AS habits_built,
                          COUNT(*) FILTER (WHERE dh.done AND dh.polarity = 'limit') AS habits_to_limit
                   FROM journal.day_habits dh WHERE dh.day = c.day) h ON true
LEFT JOIN health.daily_activity a ON a.day = c.day
LEFT JOIN spend s ON s.day = c.day
LEFT JOIN income i ON i.day = c.day;
