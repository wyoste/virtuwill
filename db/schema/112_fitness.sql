CREATE TABLE IF NOT EXISTS fitness.workout_strength (
    workout_id BIGINT NOT NULL,
    category TEXT NOT NULL DEFAULT 'strength' CHECK (category = 'strength'),
    position INTEGER NOT NULL,
    lift TEXT NOT NULL REFERENCES fitness.lifts ON UPDATE CASCADE,
    sets INTEGER NOT NULL CHECK (sets BETWEEN 1 AND 50),
    reps INTEGER CHECK (reps IS NULL OR reps BETWEEN 1 AND 1000),
    weight_lb NUMERIC CHECK (weight_lb IS NULL OR weight_lb BETWEEN 0 AND 2000),
    PRIMARY KEY (workout_id, position),
    UNIQUE (workout_id, lift),
    FOREIGN KEY (workout_id, category) REFERENCES fitness.workouts (workout_id, category) ON DELETE CASCADE
);

-- Its length is rounds × (exercises × work + (exercises − 1) × exercise rest) + (rounds − 1) × round rest.
CREATE TABLE IF NOT EXISTS fitness.workout_hiit (
    workout_id BIGINT PRIMARY KEY,
    category TEXT NOT NULL DEFAULT 'hiit' CHECK (category = 'hiit'),
    rounds INTEGER NOT NULL CHECK (rounds BETWEEN 1 AND 100),
    exercises_per_round INTEGER NOT NULL CHECK (exercises_per_round BETWEEN 1 AND 50),
    work_seconds INTEGER NOT NULL CHECK (work_seconds BETWEEN 1 AND 3600),
    exercise_rest_seconds INTEGER NOT NULL DEFAULT 0 CHECK (exercise_rest_seconds BETWEEN 0 AND 3600),
    round_rest_seconds INTEGER NOT NULL DEFAULT 0 CHECK (round_rest_seconds BETWEEN 0 AND 3600),
    total_seconds INTEGER GENERATED ALWAYS AS (
        rounds * (exercises_per_round * work_seconds + (exercises_per_round - 1) * exercise_rest_seconds)
        + (rounds - 1) * round_rest_seconds) STORED,
    FOREIGN KEY (workout_id, category) REFERENCES fitness.workouts (workout_id, category) ON DELETE CASCADE
);

-- A workout's category is its activity type's. When the activity moves to another category, the old kind's
-- facts go first (a run's distance means nothing on a lifting session), so the foreign keys always hold.
CREATE OR REPLACE FUNCTION fitness.workouts_category() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.category := (SELECT category FROM fitness.activity_types WHERE activity_type = NEW.activity_type);
    IF NEW.category IS NULL THEN
        RAISE EXCEPTION 'Unknown activity type: %', NEW.activity_type USING ERRCODE = 'foreign_key_violation';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        NEW.updated_at := now();
        IF NEW.category IS DISTINCT FROM OLD.category THEN
            DELETE FROM fitness.workout_cardio WHERE workout_id = OLD.workout_id;
            DELETE FROM fitness.workout_strength WHERE workout_id = OLD.workout_id;
            DELETE FROM fitness.workout_hiit WHERE workout_id = OLD.workout_id;
        END IF;
    END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS workouts_category ON fitness.workouts;
CREATE TRIGGER workouts_category BEFORE INSERT OR UPDATE ON fitness.workouts
    FOR EACH ROW EXECUTE FUNCTION fitness.workouts_category();

-- ── The move from journal.workouts (same ids) ───────────────────────────────
DO $$ BEGIN
    IF to_regclass('journal.workouts') IS NULL THEN
        RETURN;
    END IF;
    INSERT INTO fitness.workouts (workout_id, workout_date, started_at, activity_type, title, minutes, note, source,
                                  source_ref, details, created_at)
    SELECT w.workout_id, w.workout_date, r.started_at,
           fitness.activity_type_for(w.workout_type, COALESCE(w.details #>> '{runkeeper,type}', w.activity)),
           w.activity, w.minutes, w.note, w.source, w.source_ref, w.details, w.created_at
    FROM journal.workouts w LEFT JOIN journal.workout_routes r USING (workout_id)
    ON CONFLICT (workout_id) DO NOTHING;

    -- Every cardio workout has its cardio row, with what was known of it.
    INSERT INTO fitness.workout_cardio (workout_id, distance, distance_unit, elevation_gain_m, calories, avg_heart_rate)
    SELECT f.workout_id, w.distance, w.distance_unit, r.elevation_gain_m,
           CASE WHEN jsonb_typeof(w.details #> '{runkeeper,calories_burned}') = 'number'
                     AND (w.details #>> '{runkeeper,calories_burned}')::numeric >= 0
                THEN (w.details #>> '{runkeeper,calories_burned}')::numeric END,
           CASE WHEN jsonb_typeof(w.details #> '{runkeeper,average_heart_rate_bpm}') = 'number'
                     AND (w.details #>> '{runkeeper,average_heart_rate_bpm}')::numeric BETWEEN 20 AND 250
                THEN (w.details #>> '{runkeeper,average_heart_rate_bpm}')::numeric END
    FROM fitness.workouts f JOIN journal.workouts w USING (workout_id) LEFT JOIN journal.workout_routes r USING (workout_id)
    WHERE f.category = 'cardio'
    ON CONFLICT (workout_id) DO NOTHING;

    INSERT INTO fitness.workout_routes (workout_id, points, distance_km, elevation_gain_m, started_at, ended_at, file_name,
                                        file_asset_id, created_at)
    SELECT r.workout_id, r.points, r.distance_km, r.elevation_gain_m, r.started_at, r.ended_at, r.file_name, r.file_asset_id,
           r.created_at
    FROM journal.workout_routes r JOIN fitness.workout_cardio c USING (workout_id)
    ON CONFLICT (workout_id) DO NOTHING;

    INSERT INTO fitness.workout_strength (workout_id, position, lift, sets)
    SELECT l.workout_id, l.position, l.lift, l.sets
    FROM journal.workout_lifts l JOIN fitness.workouts f USING (workout_id) WHERE f.category = 'strength'
    ON CONFLICT DO NOTHING;

    INSERT INTO fitness.workout_hiit (workout_id, rounds, exercises_per_round, work_seconds, exercise_rest_seconds,
                                      round_rest_seconds)
    SELECT h.workout_id, h.rounds, h.exercises_per_round, h.work_seconds, h.exercise_rest_seconds, h.round_rest_seconds
    FROM journal.workout_circuits h JOIN fitness.workouts f USING (workout_id) WHERE f.category = 'hiit'
    ON CONFLICT (workout_id) DO NOTHING;

    -- New workouts number on from the moved ones.
    PERFORM setval(pg_get_serial_sequence('fitness.workouts', 'workout_id'),
                   COALESCE((SELECT MAX(workout_id) FROM fitness.workouts), 0) + 1, false);
END $$;

