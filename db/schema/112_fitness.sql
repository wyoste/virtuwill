-- The activity type for a workout described the older way: its type (Strength, Cardio, HIIT, Mobility / recovery,
-- Dog walk, Other) and what it was ("Running", "Bike", RunKeeper's "Strength Training"). The type decides where it
-- can; otherwise the words do, matched at the start of a word ("brunch" is not a run). Used by this file's move,
-- and by the app for RunKeeper and the Health tracker, so the rules live in one place.
CREATE OR REPLACE FUNCTION fitness.activity_type_for(kind TEXT, what TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN kind = 'Dog walk' THEN 'dog_walk'
        WHEN kind = 'Strength' THEN 'strength'
        WHEN kind = 'HIIT' THEN 'hiit'
        WHEN kind = 'Mobility / recovery' THEN CASE WHEN what ~* '\myoga' THEN 'yoga' ELSE 'mobility' END
        WHEN what ~* '\mdog' AND what ~* '\mwalk' THEN 'dog_walk'
        WHEN what ~* '\m(run|jog)' THEN 'run'
        WHEN what ~* '\m(bik|cycl|ride|spin)' THEN 'bike'
        WHEN what ~* '\mhik' THEN 'hike'
        WHEN what ~* '\mswim' THEN 'swim'
        WHEN what ~* '\mrow' THEN 'row'
        WHEN what ~* '\mellip' THEN 'elliptical'
        WHEN what ~* '\mwalk' THEN 'walk'
        WHEN what ~* '\m(ski|snowboard)' THEN 'ski'
        WHEN what ~* '\m(strength|weight|lift)' THEN 'strength'
        WHEN what ~* '\m(hiit|circuit|crossfit|bootcamp|boxing)' THEN 'hiit'
        WHEN what ~* '\myoga' THEN 'yoga'
        WHEN what ~* '\m(pilates|stretch|mobility|meditat)' THEN 'mobility'
        WHEN kind = 'Cardio' OR what ~* '\m(cardio|stair|arc trainer|danc|zumba|barre|skat)' THEN 'cardio'
        ELSE 'other'
    END
$$;

CREATE TABLE IF NOT EXISTS fitness.workouts (
    workout_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_date DATE NOT NULL REFERENCES core.calendar (day),
    started_at TIMESTAMPTZ,
    activity_type TEXT NOT NULL,
    category TEXT NOT NULL,                 -- the activity type's; set by fitness.workouts_category
    title TEXT NOT NULL DEFAULT '',         -- a name of your own ("Long run"); the activity's label otherwise
    minutes NUMERIC CHECK (minutes IS NULL OR minutes BETWEEN 0 AND 1440),
    note TEXT NOT NULL DEFAULT '',
    source TEXT NOT NULL CHECK (source IN ('manual', 'journal', 'health_tracker', 'runkeeper')),
    source_ref TEXT,
    details JSONB NOT NULL DEFAULT '{}',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (workout_id, category),
    FOREIGN KEY (activity_type, category) REFERENCES fitness.activity_types (activity_type, category) ON UPDATE CASCADE
);
CREATE INDEX IF NOT EXISTS workouts_by_date ON fitness.workouts (workout_date);
CREATE INDEX IF NOT EXISTS workouts_by_source ON fitness.workouts (source, workout_date);
-- An imported record keeps its row (and id) across loads.
CREATE UNIQUE INDEX IF NOT EXISTS workouts_by_tracker_ref ON fitness.workouts (source_ref) WHERE source = 'health_tracker';
CREATE UNIQUE INDEX IF NOT EXISTS workouts_by_runkeeper_ref ON fitness.workouts (source_ref) WHERE source = 'runkeeper';

CREATE TABLE IF NOT EXISTS fitness.workout_cardio (
    workout_id BIGINT PRIMARY KEY,
    category TEXT NOT NULL DEFAULT 'cardio' CHECK (category = 'cardio'),
    distance NUMERIC CHECK (distance IS NULL OR distance BETWEEN 0 AND 1000),
    distance_unit TEXT NOT NULL DEFAULT 'mi' CHECK (distance_unit IN ('mi', 'km')),
    -- The canonical distance for every calculation; distance and distance_unit keep what was entered.
    distance_km NUMERIC GENERATED ALWAYS AS (CASE distance_unit WHEN 'mi' THEN distance * 1.609344 ELSE distance END) STORED,
    elevation_gain_m NUMERIC,
    calories NUMERIC CHECK (calories IS NULL OR calories >= 0),
    avg_heart_rate NUMERIC CHECK (avg_heart_rate IS NULL OR avg_heart_rate BETWEEN 20 AND 250),
    FOREIGN KEY (workout_id, category) REFERENCES fitness.workouts (workout_id, category) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS fitness.workout_routes (
    workout_id BIGINT PRIMARY KEY REFERENCES fitness.workout_cardio ON DELETE CASCADE,
    points JSONB NOT NULL CHECK (jsonb_typeof(points) = 'array'),   -- [[lat, lng], …], simplified for drawing
    distance_km NUMERIC,                                            -- measured along the full track
    elevation_gain_m NUMERIC,
    started_at TIMESTAMPTZ,
    ended_at TIMESTAMPTZ,
    file_name TEXT NOT NULL DEFAULT '',
    file_asset_id BIGINT REFERENCES core.media_assets ON DELETE SET NULL,   -- an uploaded file; RunKeeper's stay in bronze
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

