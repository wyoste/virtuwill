-- VirtuWill data model · fitness: one base table for every workout, a fact table per kind
--
--   fitness.categories       cardio · strength (lifting) · hiit · mobility (yoga) · other
--   fitness.activity_types   what was done: run, walk, dog walk, bike … each in one category,
--                            and whether it counts toward the workout goal (a dog walk doesn't)
--   fitness.workouts         one row per session, whatever its kind: date, activity, minutes, note, source
--   fitness.workout_cardio   1:1 for cardio: distance, climbing, calories, heart rate
--   fitness.workout_routes   1:1 with a cardio row: the GPS line, from a GPX/TCX file or RunKeeper
--   fitness.workout_strength one row per lift: sets (reps and weight when known)
--   fitness.workout_hiit     1:1 for HIIT: the circuit
--   fitness.workout_sessions the view the screens and the API read: a workout with all of its facts
--
-- Each fact table carries its category and points at (workout_id, category), so a cardio row can
-- only belong to a cardio workout. A workout's category follows its activity type, and changing
-- the activity to another category drops the old kind's facts (fitness.workouts_category trigger).
--
-- This replaces journal.workouts (with workout_types, workout_routes, workout_lifts and
-- workout_circuits), whose rows move here with the same ids. Its free-text activity
-- ("Running", "Bike") becomes an activity type (fitness.activity_type_for), and is kept as the title.

CREATE SCHEMA IF NOT EXISTS fitness;

